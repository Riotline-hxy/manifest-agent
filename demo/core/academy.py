_BY_ID = {a["id"]: a for a in ARTICLES}


def catalog() -> list[dict]:
    return [{"id": a["id"], "title": a["title"], "chapter": a["chapter"], "minutes": a["minutes"],
             "tags": a["tags"], "summary": a["summary"]} for a in ARTICLES]


def get(article_id: str) -> dict | None:
    return _BY_ID.get(article_id)


def search(query: str, k: int = 3) -> list[dict]:
    """Small, transparent scorer: title/tag/summary/body hits. No model involved,
    so 小光 can never invent an article."""
    q = (query or "").strip().lower()
    if not q:
        return []
    terms = [q]
    for sep in ("什么", "怎么", "如何", "意思", "是", "的", "吗", "呢", "？", "?", "，", "。", "、", " "):
        terms = [p for t in terms for p in t.split(sep)]
    # 中文没有空格：整句往往匹配不到，补上二元组
    bigrams = [q[i:i + 2] for i in range(len(q) - 1)] if len(q) > 3 else []
    terms = [t for t in terms if len(t) >= 2] + bigrams
    seen, uniq = set(), []
    for t in terms:
        if t not in seen:
            seen.add(t)
            uniq.append(t)
    terms = uniq
    scored = []
    for a in ARTICLES:
        hay = (a["title"] + " " + " ".join(a["tags"]) + " " + a["summary"] + " " + a["source"]).lower()
        body = " ".join(a["body"]).lower()
        score = 0
        for t in terms:
            if t in hay:
                score += 3
            elif t in body:
                score += 1
        if q in a["title"].lower():
            score += 5
        if score >= 3:
            scored.append((score, a))
    scored.sort(key=lambda x: -x[0])
    return [{"id": a["id"], "title": a["title"], "chapter": a["chapter"],
             "summary": a["summary"], "source": a["source"]} for _, a in scored[:k]]
