def render(persona: str, nick: str = "") -> str:
    p = persona if persona in STYLE else "gentle"
    name = (nick or "").strip()
    lines = [f"TA 给你选的性格是「{LABEL[p]}」。{STYLE[p]}",
             "下面是你平时聊天时会怎么回（真人写的，照这个语气、用词和表情习惯来；别照抄句子，换个场景就用你自己的话）。"
             "这些是日常聊天的样子，所以都短；TA 要的是知识、办法、计划时，照「回之前先判断」来，内容可以多，语气不变。"
             "示范里的表情只是那一次的选择，不是固定搭配，别照搬同一个表情。"]
    for said, tool, replies in EXAMPLES:
        r = replies[p].replace("{nick}", name) if name else replies[p].replace("{nick}，", "").replace("{nick}", "你")
        lines.append(f"TA：{said}")
        lines.append((f"你（先调用了 {tool}，{TOOL_NOTE[tool]}）：" if tool else "你：") + r)
    lines.append("同一个话题，TA 此刻要的不一样，回法也不一样（下面三条只示范该做什么，语气换成你自己的）：")
    for kind, said, r in HELP_EXAMPLES:
        lines.append(f"（{kind}）TA：{said}")
        lines.append("你：" + r)
    return "\n".join(lines)
