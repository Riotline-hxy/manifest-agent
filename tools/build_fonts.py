"""Build the self-hosted rounded webfonts.

    python tools/build_fonts.py <dir with RHR-CN.7z and Nunito.ttf> <dir with py7zr>

Resource Han Rounded CN (SIL OFL 1.1) is ~20MB per weight, so it is cut into
unicode-range slices the way Google Fonts serves CJK: slice 0 holds every
character the app's own copy uses (plus punctuation), the rest of GB2312 is
split into ~450-character slices ordered by frequency
(jieba_dict.txt in the work dir), so ordinary text mostly hits slices 1–3. A browser only downloads the slices whose
characters actually appear on the page. Nunito (OFL) covers Latin and digits.
Output: demo/public/fonts/*.woff2 + demo/public/css/fonts.css
"""
import pathlib
import re
import sys

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "demo" / "public" / "fonts"
CSS = ROOT / "demo" / "public" / "css" / "fonts.css"
WEIGHTS = {"Medium": 500, "Bold": 700}
SLICE = 450


def gb2312_chars() -> list[str]:
    out = []
    for hi in range(0xB0, 0xF8):
        for lo in range(0xA1, 0xFF):
            try:
                out.append(bytes([hi, lo]).decode("gb2312"))
            except UnicodeDecodeError:
                pass
    return out


def char_freq(work: pathlib.Path) -> dict[str, int]:
    """Character frequency from jieba's word list (word freq summed per char).
    Only used to order slices so everyday text lands in the first few."""
    f = work / "jieba_dict.txt"
    freq: dict[str, int] = {}
    if f.exists():
        for line in f.read_text(encoding="utf-8").splitlines():
            parts = line.split(" ")
            if len(parts) >= 2 and parts[1].isdigit():
                n = int(parts[1])
                for ch in parts[0]:
                    freq[ch] = freq.get(ch, 0) + n
    return freq


def app_chars() -> set[str]:
    chars: set[str] = set()
    for pat in ("demo/public/**/*.js", "demo/public/**/*.html", "demo/core/*.py", "demo/routes.py"):
        for f in ROOT.glob(pat):
            if "vendor" in f.parts:
                continue
            chars.update(re.findall(r"[　-〿一-鿿＀-￯‘-‟…·]",
                                    f.read_text(encoding="utf-8", errors="ignore")))
    return chars


def ranges(cps: list[int]) -> str:
    cps = sorted(set(cps))
    out, start, prev = [], None, None
    for c in cps:
        if start is None:
            start = prev = c
        elif c == prev + 1:
            prev = c
        else:
            out.append((start, prev))
            start = prev = c
    if start is not None:
        out.append((start, prev))
    return ", ".join(f"U+{a:X}" if a == b else f"U+{a:X}-{b:X}" for a, b in out)


def cut(src: pathlib.Path, cps: list[int], dest: pathlib.Path) -> int:
    opts = subset.Options()
    opts.flavor = "woff2"
    opts.layout_features = ["*"]
    opts.name_IDs = ["*"]
    opts.hinting = False
    opts.desubroutinize = True
    font = TTFont(src)
    sub = subset.Subsetter(opts)
    sub.populate(unicodes=cps)
    sub.subset(font)
    font.flavor = "woff2"
    font.save(dest)
    return dest.stat().st_size


def main() -> int:
    work = pathlib.Path(sys.argv[1])
    sys.path.insert(0, sys.argv[2])
    import py7zr

    names = [f"ResourceHanRoundedCN-{w}.ttf" for w in WEIGHTS]
    if not all((work / n).exists() for n in names):
        with py7zr.SevenZipFile(work / "RHR-CN.7z") as z:
            z.extract(path=work, targets=names)
    OUT.mkdir(parents=True, exist_ok=True)
    for f in OUT.glob("*.woff2"):
        f.unlink()

    used = app_chars()
    punct = [chr(c) for c in range(0x3000, 0x3040)] + [chr(c) for c in range(0xFF01, 0xFF5F)] + list("“”‘’…·—")
    first = sorted(set(used) | set(punct), key=ord)
    freq = char_freq(work)
    rest = [c for c in gb2312_chars() if c not in set(first) and "一" <= c <= "鿿"]
    rest.sort(key=lambda c: -freq.get(c, 0))
    slices = [first] + [rest[i:i + SLICE] for i in range(0, len(rest), SLICE)]

    css = ["/* generated by tools/build_fonts.py — Resource Han Rounded CN + Nunito, both SIL OFL 1.1 */"]
    total = 0
    for wname, wnum in WEIGHTS.items():
        src = work / f"ResourceHanRoundedCN-{wname}.ttf"
        for i, chars in enumerate(slices):
            cps = [ord(c) for c in chars]
            dest = OUT / f"rhr-{wnum}-{i:02d}.woff2"
            total += cut(src, cps, dest)
            css.append("@font-face{font-family:\"XG Rounded\";font-style:normal;font-weight:%d;font-display:swap;"
                       "src:url(../fonts/%s) format(\"woff2\");unicode-range:%s}" % (wnum, dest.name, ranges(cps)))
    # Nunito: Latin + digits + common symbols; variable weight axis kept
    nun = OUT / "nunito.woff2"
    latin = list(range(0x20, 0x7F)) + list(range(0xA0, 0x100)) + [0x2013, 0x2014, 0x2022, 0x2192, 0x2190, 0x00D7]
    total += cut(work / "Nunito.ttf", latin, nun)
    css.insert(1, "@font-face{font-family:\"Nunito\";font-style:normal;font-weight:300 1000;font-display:swap;"
                  "src:url(../fonts/nunito.woff2) format(\"woff2\");unicode-range:%s}" % ranges(latin))
    CSS.write_text("\n".join(css) + "\n", encoding="utf-8")
    print(f"{len(slices)} slices x {len(WEIGHTS)} weights + nunito; first slice {len(first)} chars; "
          f"total {total // 1024} KB; slice0 sizes:",
          [(p.name, p.stat().st_size // 1024) for p in sorted(OUT.glob('rhr-*-00.woff2'))])
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
